def isle_h(x, y):
    """Height above the sea at island-local x, y."""
    r = math.hypot(x, y) / ISLE_R
    h = 2.6 + 2.2 * noise.noise(Vector((x * 0.045, y * 0.045, 3.1))) + 0.8 * noise.noise(Vector((x * 0.13, y * 0.13, 9.0)))
    h += 9.0 * math.exp(-((x + 24) ** 2 + (y - 6) ** 2) / (9.5 ** 2))   # lightning hill
    edge = max(0.0, 1 - r ** 2.4)
    return h * edge - 0.7 * (1 - edge)


