def build_pig():
    root = empty('pig')
    torso = sphere((0, 0, 0), (1.38, 1.05, 0.98), SKIN, root, seg=64)
    sphere((-0.25, 0, -0.18), (1.05, 0.98, 0.85), SKIN, root)  # belly
    head = empty('head', (1.22, 0, 0.3), root)
    head.rotation_euler = (0, 0, math.radians(-20))  # glance toward the lens
    sphere((0, 0, 0), 0.7, SKIN, head)
    cylinder((0.66, 0, -0.1), 0.33, 0.34, ROSE, head, rot=(0, math.pi / 2, 0), r2=0.29)
    sphere((0.83, 0, -0.1), (0.05, 0.29, 0.29), ROSE, head)  # rounded snout face
    for s in (-1, 1):
        sphere((0.86, s * 0.11, -0.08), (0.03, 0.055, 0.075), HOOF, head)   # nostrils
        sphere((0.53, s * 0.31, 0.24), 0.15, EYE, head)
        sphere((0.655, s * 0.29, 0.31), 0.04, GLINT, head)
        sphere((0.34, s * 0.52, -0.12), (0.2, 0.06, 0.16), ROSE, head)        # cheek blush
        ear = cylinder((0.0, s * 0.44, 0.62), 0.24, 0.5, ROSE, head, r2=0.02, rot=(-s * 0.55, 0.35, 0))
        ear.scale = (1, 0.55, 1)
    # mouth: a small happy curve
    cu = bpy.data.curves.new('smile', 'CURVE')
    cu.dimensions = '3D'
    cu.bevel_depth = 0.026
    sp = cu.splines.new('NURBS')
    pts = [(0.52, -0.2, -0.36), (0.6, -0.1, -0.44), (0.62, 0, -0.46), (0.6, 0.1, -0.44), (0.52, 0.2, -0.36)]
    sp.points.add(len(pts) - 1)
    for p, c in zip(sp.points, pts):
        p.co = (*c, 1)
    sp.use_endpoint_u = True
    sm = bpy.data.objects.new('smile', cu)
    sm.data.materials.append(HOOF)
    col.objects.link(sm)
    sm.parent = head

    # legs, tucked for flight
    for sx, tilt in ((0.72, 1.0), (-0.68, -1.05)):
        for sy in (-1, 1):
            hip = empty('hip', (sx, sy * 0.52, -0.62), root)
            hip.rotation_euler = (0, -tilt, 0)
            cylinder((0, 0, -0.3), 0.21, 0.62, SKIN, hip, r2=0.18)
            sphere((0, 0, 0), 0.23, SKIN, hip)
            cylinder((0, 0, -0.66), 0.19, 0.16, HOOF, hip, r2=0.2)

    # curly tail
    cu = bpy.data.curves.new('tail', 'CURVE')
    cu.dimensions = '3D'
    cu.bevel_depth = 0.05
    cu.bevel_resolution = 6
    sp = cu.splines.new('NURBS')
    n = 28
    sp.points.add(n - 1)
    for i, p in enumerate(sp.points):
        t = i / (n - 1)
        a = t * math.pi * 4.2
        p.co = (-1.3 - t * 0.5, math.cos(a) * 0.17, 0.25 + math.sin(a) * 0.17 + t * 0.12, 1)
    sp.use_endpoint_u = True
    tail = bpy.data.objects.new('tail', cu)
    tail.data.materials.append(ROSE)
    col.objects.link(tail)
    tail.parent = root

    # wings: three layered rows of feathers on each side, mid-upstroke
    for s in (-1, 1):
        shoulder = empty('wing', (0.2, s * 0.72, 0.62), root)
        shoulder.scale = (0.82, 0.82, 0.82)
        shoulder.rotation_euler = (s * (0.98 if s > 0 else 0.38), 0, s * -0.12)  # far wing high, near wing lower, so both read
        sphere((0, s * 0.25, 0.02), (0.42, 0.4, 0.14), FEATHER, shoulder)
        rows = (
            (9, 2.9, 1.5, 0.27, 0.0, FEATHER),        # primaries: count, longest, shortest, width, z
            (7, 1.9, 1.0, 0.27, 0.05, FEATHER),
            (6, 1.15, 0.7, 0.25, 0.1, FEATHER_TIP),
        )
        for count, long, short, width, z, m in rows:
            for i in range(count):
                t = i / (count - 1)
                length = long - (long - short) * (t ** 1.3)
                holder = empty('f', (0, 0, z), shoulder)
                # fan from slightly forward to swept well back
                holder.rotation_euler = (0, 0, s * (-0.22 + t * 1.5))
                f = sphere((0, s * (length / 2 + 0.15), -t * 0.03), (width, length / 2, 0.035), m, holder, seg=24)
                f.rotation_euler = (0, 0.12, 0)
    return root


