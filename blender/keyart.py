# ------------------------------------------------------------------ helpers
def principled(name, color, rough=0.5, **inputs):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    b = next(n for n in m.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
    b.inputs['Base Color'].default_value = (*color, 1)
    b.inputs['Roughness'].default_value = rough
    for k, v in inputs.items():
        key = k.replace('_', ' ')
        if key in b.inputs:
            b.inputs[key].default_value = v
        else:
            print('WARN: no principled input', key)
    return m


def emission(name, color, strength):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    e = nt.nodes.new('ShaderNodeEmission')
    e.inputs['Color'].default_value = (*color, 1)
    e.inputs['Strength'].default_value = strength
    o = nt.nodes.new('ShaderNodeOutputMaterial')
    nt.links.new(e.outputs[0], o.inputs['Surface'])
    return m


def finish(ob, mat, parent=None, smooth=True, subsurf=0):
    if mat:
        ob.data.materials.append(mat)
    if smooth and hasattr(ob.data, 'polygons'):
        ob.data.polygons.foreach_set('use_smooth', [True] * len(ob.data.polygons))
    if subsurf:
        mod = ob.modifiers.new('sub', 'SUBSURF')
        mod.levels = mod.render_levels = subsurf
    if parent:
        ob.parent = parent
    return ob


_mesh_cache = {}


def _shared(key, make, mat, smooth):
    """One mesh per (shape, material); every further use is a cheap linked object."""
    k = (key, mat.name if mat else None, smooth)
    if k not in _mesh_cache:
        bm = bmesh.new()
        make(bm)
        me = bpy.data.meshes.new(str(key))
        bm.to_mesh(me)
        bm.free()
        if mat:
            me.materials.append(mat)
        if smooth:
            me.polygons.foreach_set('use_smooth', [True] * len(me.polygons))
        _mesh_cache[k] = me
    return _mesh_cache[k]


def _place(me, loc, scale, parent, rot=(0, 0, 0)):
    ob = bpy.data.objects.new(me.name, me)
    ob.location = loc
    ob.rotation_euler = rot
    ob.scale = scale if isinstance(scale, (tuple, list, Vector)) else (scale,) * 3
    col.objects.link(ob)
    if parent:
        ob.parent = parent
    return ob


def sphere(loc, scale, mat, parent=None, rot=(0, 0, 0), seg=48):
    me = _shared(('uv', seg), lambda bm: bmesh.ops.create_uvsphere(bm, u_segments=seg, v_segments=seg // 2, radius=1), mat, True)
    return _place(me, loc, scale, parent, rot)


def ico(loc, scale, mat, parent=None, sub=3, smooth=True):
    me = _shared(('ico', sub), lambda bm: bmesh.ops.create_icosphere(bm, subdivisions=sub, radius=1), mat, smooth)
    return _place(me, loc, scale, parent)


def cylinder(loc, r, depth, mat, parent=None, rot=(0, 0, 0), r2=None, verts=32):
    if r2 is None:
        bpy.ops.mesh.primitive_cylinder_add(vertices=verts, radius=r, depth=depth, location=loc, rotation=rot)
    else:
        bpy.ops.mesh.primitive_cone_add(vertices=verts, radius1=r, radius2=r2, depth=depth, location=loc, rotation=rot)
    return finish(bpy.context.active_object, mat, parent)


def box(loc, size, mat, parent=None, rot=(0, 0, 0)):
    bpy.ops.mesh.primitive_cube_add(size=1, location=loc, rotation=rot)
    ob = bpy.context.active_object
    ob.scale = size
    return finish(ob, mat, parent, smooth=False)


def empty(name, loc=(0, 0, 0), parent=None):
    e = bpy.data.objects.new(name, None)
    e.location = loc
    col.objects.link(e)
    if parent:
        e.parent = parent
    return e


def aim(ob, direction):
    """Point an object's -Z (lights, cameras) along a direction."""
    ob.rotation_euler = Vector(direction).to_track_quat('-Z', 'Y').to_euler()


